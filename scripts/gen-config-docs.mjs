#!/usr/bin/env node
// scripts/gen-config-docs.mjs
// R3: regenerates the TS-side table in docs/CONFIGURATION.md from
// CinderpawAgent/src/config.ts CONFIG_SCHEMA. Rust-side vars are hand-maintained
// (separate section, this script does not touch it).
import { readFileSync, writeFileSync } from "node:fs";

const CONFIG_TS_URL = new URL("../CinderpawAgent/src/config.ts", import.meta.url);
const DOC_URL = new URL("../docs/CONFIGURATION.md", import.meta.url);

export function parseConfigSchema(configSrc) {
  const match = configSrc.match(/CONFIG_SCHEMA: ConfigEntry\[\] = \[([\s\S]*?)\n\];/);
  if (!match) throw new Error("CONFIG_SCHEMA not found in config.ts");
  const entryRe = /\{\s*name:\s*"([^"]+)",\s*type:\s*"([^"]+)",\s*default:\s*([^,]+),\s*description:\s*"((?:[^"\\]|\\.)*)",\s*security:\s*(true|false)\s*\}/g;
  return [...match[1].matchAll(entryRe)].map((m) => ({
    name: m[1],
    type: m[2],
    default: m[3].trim(),
    description: m[4].replace(/\\"/g, '"'),
    security: m[5] === "true",
  }));
}

export function renderTable(rows) {
  return [
    "<!-- AUTO-GENERATED by scripts/gen-config-docs.mjs from CinderpawAgent/src/config.ts. Do not hand-edit this section. -->",
    "",
    "| Var | Type | Default | Security | Description |",
    "|---|---|---|---|---|",
    ...rows.map((r) => `| \`${r.name}\` | ${r.type} | \`${r.default}\` | ${r.security ? "yes" : ""} | ${r.description} |`),
  ].join("\n");
}

function main() {
  const configSrc = readFileSync(CONFIG_TS_URL, "utf8");
  const rows = parseConfigSchema(configSrc);
  const body = renderTable(rows);

  const existing = readFileSync(DOC_URL, "utf8");
  const marker = "<!-- TS-SCHEMA-TABLE -->";
  const endMarker = "<!-- /TS-SCHEMA-TABLE -->";
  if (!existing.includes(marker)) {
    throw new Error(`docs/CONFIGURATION.md missing ${marker} — add it where the generated table should go`);
  }
  const [before, after] = existing.split(marker);
  const rest = after.split(endMarker)[1] ?? "";
  writeFileSync(DOC_URL, `${before}${marker}\n${body}\n${endMarker}${rest}`);
  console.log(`wrote ${rows.length} rows to docs/CONFIGURATION.md`);
}

if (import.meta.url === `file://${process.argv[1].replace(/\\/g, "/")}` || process.argv[1]?.endsWith("gen-config-docs.mjs")) {
  main();
}
